# -*- coding: utf-8 -*-
from odoo import models, fields, api
import base64


class DashboardBuilderReport(models.AbstractModel):
    _name = 'report.el_dashboard_builder.dashboard_report'
    _description = 'Dashboard Builder Report'

    @api.model
    def _get_report_values(self, docids, data=None):
        docs = self.env['dashboard.builder'].browse(docids)
        return {
            'doc_ids': docids,
            'doc_model': 'dashboard.builder',
            'docs': docs,
            'data': data or {},
        }

    def generate_dashboard_pdf(self, dashboard_id):
        """Generate PDF report for a dashboard."""
        dashboard = self.env['dashboard.builder'].browse(dashboard_id)
        if not dashboard.exists():
            return None

        try:
            pdf_content, _ = self.env['ir.actions.report']._render_qweb_pdf(
                'el_dashboard_builder.action_report_dashboard', [dashboard.id]
            )
            return pdf_content
        except Exception:  # noqa: BLE001 - fall back when no PDF engine is installed
            return self._generate_fallback_pdf(dashboard)

    def _generate_fallback_pdf(self, dashboard):
        """Build a simple PDF without an external wkhtmltopdf installation."""
        import io
        from xml.sax.saxutils import escape
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

        output = io.BytesIO()
        document = SimpleDocTemplate(
            output,
            pagesize=A4,
            leftMargin=18 * mm,
            rightMargin=18 * mm,
            topMargin=18 * mm,
            bottomMargin=18 * mm,
            title=dashboard.name,
        )
        styles = getSampleStyleSheet()
        story = [
            Paragraph(escape(dashboard.name or 'Dashboard'), styles['Title']),
        ]
        if dashboard.description:
            story.extend([Spacer(1, 4 * mm), Paragraph(escape(dashboard.description), styles['BodyText'])])
        story.append(Spacer(1, 6 * mm))

        info_rows = [
            ['Owner', dashboard.user_id.name or ''],
            ['Company', dashboard.company_id.name or ''],
            ['Created', dashboard.create_date.strftime('%Y-%m-%d %H:%M') if dashboard.create_date else ''],
            ['Last viewed', dashboard.last_viewed.strftime('%Y-%m-%d %H:%M') if dashboard.last_viewed else 'Never'],
            ['Views', str(dashboard.view_count or 0)],
        ]
        info_table = Table(info_rows, colWidths=[35 * mm, 130 * mm])
        info_table.setStyle(TableStyle([
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('LINEBELOW', (0, 0), (-1, -1), 0.25, colors.HexColor('#d8dee5')),
        ]))
        story.extend([info_table, Spacer(1, 7 * mm)])

        story.append(Paragraph('Widgets', styles['Heading2']))
        items = dashboard.item_ids.filtered('is_visible').sorted(key=lambda item: (item.pos_y, item.pos_x))
        widget_rows = [['Widget', 'Category', 'Position', 'Size']]
        for item in items:
            widget = item.widget_id
            widget_rows.append([
                widget.name if widget else (item.custom_widget_name or 'Widget'),
                widget.category if widget else 'custom',
                '%s, %s' % (item.pos_x, item.pos_y),
                '%s x %s' % (item.width, item.height),
            ])
        if len(widget_rows) == 1:
            widget_rows.append(['No visible widgets', '', '', ''])

        items_table = Table(widget_rows, colWidths=[75 * mm, 35 * mm, 30 * mm, 25 * mm], repeatRows=1)
        items_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#eef2f6')),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('GRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#d8dee5')),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(items_table)
        story.extend([Spacer(1, 8 * mm), Paragraph(
            'Generated by Dashboard Builder on %s' % fields.Datetime.now().strftime('%Y-%m-%d %H:%M'),
            styles['Italic'],
        )])
        document.build(story)
        return output.getvalue()

    def generate_dashboard_excel(self, dashboard_id):
        """Generate Excel report for a dashboard."""
        import io
        import xlsxwriter
        
        dashboard = self.env['dashboard.builder'].browse(dashboard_id)
        if not dashboard.exists():
            return None
        
        output = io.BytesIO()
        workbook = xlsxwriter.Workbook(output, {'in_memory': True})
        
        # Dashboard Info Sheet
        info_sheet = workbook.add_worksheet('Dashboard Info')
        info_sheet.write(0, 0, 'Property')
        info_sheet.write(0, 1, 'Value')
        
        info_data = [
            ('Name', dashboard.name),
            ('Description', dashboard.description or ''),
            ('Owner', dashboard.user_id.name),
            ('Company', dashboard.company_id.name),
            ('Created', dashboard.create_date.strftime('%Y-%m-%d %H:%M') if dashboard.create_date else ''),
            ('Last Viewed', dashboard.last_viewed.strftime('%Y-%m-%d %H:%M') if dashboard.last_viewed else 'Never'),
            ('View Count', dashboard.view_count),
            ('Public', 'Yes' if dashboard.is_public else 'No'),
            ('Refresh Interval', f'{dashboard.refresh_interval}s' if dashboard.refresh_interval else 'Disabled'),
        ]
        
        for row, (key, value) in enumerate(info_data, 1):
            info_sheet.write(row, 0, key)
            info_sheet.write(row, 1, value)
        
        # Widgets Sheet
        widgets_sheet = workbook.add_worksheet('Widgets')
        widgets_sheet.write(0, 0, 'Widget')
        widgets_sheet.write(0, 1, 'Type')
        widgets_sheet.write(0, 2, 'Position (X, Y)')
        widgets_sheet.write(0, 3, 'Size (W x H)')
        widgets_sheet.write(0, 4, 'Configuration')
        
        for row, item in enumerate(dashboard.item_ids.filtered('is_visible'), 1):
            widgets_sheet.write(row, 0, item.widget_id.name if item.widget_id else item.custom_widget_name)
            widgets_sheet.write(row, 1, item.widget_id.category if item.widget_id else 'custom')
            widgets_sheet.write(row, 2, f'{item.pos_x}, {item.pos_y}')
            widgets_sheet.write(row, 3, f'{item.width} x {item.height}')
            widgets_sheet.write(row, 4, str(item.config))
        
        workbook.close()
        output.seek(0)
        return output.read()


class DashboardExportWizard(models.TransientModel):
    _name = 'dashboard.builder.export.wizard'
    _description = 'Dashboard Export Wizard'

    dashboard_id = fields.Many2one(
        'dashboard.builder',
        string='Dashboard',
        required=True,
    )
    export_format = fields.Selection([
        ('pdf', 'PDF'),
        ('excel', 'Excel'),
        ('json', 'JSON'),
    ], string='Export Format', required=True, default='pdf')
    include_data = fields.Boolean(
        string='Include Widget Data',
        default=True,
    )

    def action_export(self):
        """Export dashboard in selected format."""
        self.ensure_one()
        dashboard = self.dashboard_id
        
        if self.export_format == 'pdf':
            pdf_content = self.env['report.el_dashboard_builder.dashboard_report'].generate_dashboard_pdf(dashboard.id)
            if pdf_content:
                attachment = self.env['ir.attachment'].create({
                    'name': f'{dashboard.name}.pdf',
                    'type': 'binary',
                    'datas': base64.b64encode(pdf_content),
                    'res_model': 'dashboard.builder',
                    'res_id': dashboard.id,
                    'mimetype': 'application/pdf',
                })
                return {
                    'type': 'ir.actions.act_url',
                    'url': f'/web/content/{attachment.id}?download=true',
                    'target': 'self',
                }
        
        elif self.export_format == 'excel':
            excel_content = self.env['report.el_dashboard_builder.dashboard_report'].generate_dashboard_excel(dashboard.id)
            if excel_content:
                attachment = self.env['ir.attachment'].create({
                    'name': f'{dashboard.name}.xlsx',
                    'type': 'binary',
                    'datas': base64.b64encode(excel_content),
                    'res_model': 'dashboard.builder',
                    'res_id': dashboard.id,
                    'mimetype': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
                })
                return {
                    'type': 'ir.actions.act_url',
                    'url': f'/web/content/{attachment.id}?download=true',
                    'target': 'self',
                }
        
        elif self.export_format == 'json':
            # Return JSON export action
            return {
                'type': 'ir.actions.act_url',
                'url': f'/dashboard/builder/export/{dashboard.id}',
                'target': 'self',
            }
        
        return {'type': 'ir.actions.act_window_close'}